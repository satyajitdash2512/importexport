import type { KpiTileDef, FieldDef } from '../components/primitives';

export interface ColSpec {
  field: string; header: string; width?: number; flex?: number; minWidth?: number;
  kind?: 'text' | 'money' | 'variance' | 'number' | 'qty' | 'pct' | 'date' | 'status' | 'severity' | 'chip' | 'bool' | 'link' | 'list';
  currencyField?: string; unit?: string; unitField?: string; dp?: number; to?: (row: any) => string;
}

export interface ScreenSpec {
  path: string;
  title: string;
  subtitle?: string;
  rdRef?: string;
  /** API path; omit for a statically defined screen. */
  endpoint?: string;
  /** Extract the row array from the API payload. */
  pick?: (data: any) => any[];
  /** Static rows where no endpoint exists yet. */
  rows?: any[];
  columns: ColSpec[];
  searchFields?: string[];
  tiles?: (rows: any[], data?: any) => KpiTileDef[];
  fields?: FieldDef[];
  fieldsTitle?: string;
  actions?: string[];
  primaryAction?: string;
  newRoute?: string;
  rowRoute?: (row: any) => string;
  rowClassName?: (row: any) => string | undefined;
  note?: string;
  noteSeverity?: 'info' | 'warning' | 'error' | 'success';
  footnote?: string;
  emptyTitle?: string;
  emptyDetail?: string;
  pageSize?: number;
  /**
   * Page, search and count on the server instead of loading the whole list into
   * the browser. Set on high-volume screens (voucher register, trade partners,
   * shipments) so they scale to millions of rows. The endpoint must return a
   * `page: { total, limit, offset }` envelope and honour `limit`/`offset`/`q`.
   */
  serverPaged?: boolean;
}

const money = (field: string, header: string, width = 130): ColSpec => ({ field, header, width, kind: 'money' });

